#!/usr/bin/env node
// Kavrvix SEO generator — no dependencies.
//
//   node scripts/seo.mjs https://yourdomain.com   -> saves the domain and rebuilds everything
//   node scripts/seo.mjs                          -> rebuilds with the domain already saved
//
// It rewrites the block between <!-- seo:start --> and <!-- seo:end --> in index.html
// (canonical, og:url, absolute share images, JSON-LD structured data) and writes
// sitemap.xml + robots.txt. Edit site.config.json for names, socials and descriptions.

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const cfgPath = join(root, "site.config.json");
const cfg = JSON.parse(readFileSync(cfgPath, "utf8"));

const arg = process.argv[2];
if (arg) {
  if (!/^https:\/\/[^/\s]+\.[^/\s]+/.test(arg)) {
    console.error("Give the full domain, starting with https://  e.g. node scripts/seo.mjs https://kavrvix.com");
    process.exit(1);
  }
  cfg.url = arg.replace(/\/+$/, "");
  writeFileSync(cfgPath, JSON.stringify(cfg, null, 2) + "\n");
}
const url = (cfg.url || "").replace(/\/+$/, "");
const abs = (p) => (url ? `${url}/${p.replace(/^\//, "")}` : p);

const htmlPath = join(root, "index.html");
let html = readFileSync(htmlPath, "utf8");

const decode = (s) => s.replace(/<[^>]+>/g, "").replace(/&amp;/g, "&").replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&quot;/g, '"').replace(/&#39;/g, "'").trim();

// FAQ from the page itself, so the structured data always matches what people see
const faqs = [...html.matchAll(/<summary>([\s\S]*?)<span class="pm"><\/span><\/summary><p class="ans">([\s\S]*?)<\/p>/g)]
  .map((m) => ({ q: decode(m[1]), a: decode(m[2]) }));

// Services (experts site) from the SERVICES list in the page script
const services = [...html.matchAll(/name:"([^"]+)", tag:"([^"]+)"/g)].map((m) => ({ name: m[1], description: m[2] }));

const org = {
  "@type": "Organization",
  "@id": url ? `${url}/#org` : "#org",
  name: cfg.org,
  ...(url && { url, logo: abs("brand/icon-512.png") }),
  sameAs: cfg.socials,
  contactPoint: [{ "@type": "ContactPoint", contactType: "customer support", telephone: cfg.phone, availableLanguage: ["English"] }],
};
const graph = [
  org,
  { "@type": "WebSite", name: cfg.name, ...(url && { url }), publisher: { "@id": org["@id"] }, inLanguage: "en" },
  {
    "@type": "Service",
    name: cfg.serviceName,
    serviceType: cfg.serviceType,
    description: cfg.description,
    provider: { "@id": org["@id"] },
    areaServed: "Worldwide",
    ...(url && { url }),
    ...(services.length && {
      hasOfferCatalog: {
        "@type": "OfferCatalog",
        name: cfg.serviceName,
        itemListElement: services.map((s) => ({ "@type": "Offer", itemOffered: { "@type": "Service", name: s.name, description: s.description } })),
      },
    }),
  },
];
if (faqs.length) {
  graph.push({
    "@type": "FAQPage",
    mainEntity: faqs.map((f) => ({ "@type": "Question", name: f.q, acceptedAnswer: { "@type": "Answer", text: f.a } })),
  });
}

const block = [
  "<!-- seo:start (generated by scripts/seo.mjs, do not edit by hand) -->",
  url ? `<link rel="canonical" href="${url}/">` : "<!-- canonical + og:url appear here once you run: node scripts/seo.mjs https://yourdomain.com -->",
  url ? `<meta property="og:url" content="${url}/">` : "",
  `<meta property="og:image" content="${abs("og-image.png")}">`,
  `<meta property="og:image:alt" content="${cfg.ogAlt}">`,
  `<meta name="twitter:image" content="${abs("og-image.png")}">`,
  `<script type="application/ld+json">${JSON.stringify({ "@context": "https://schema.org", "@graph": graph })}</script>`,
  "<!-- seo:end -->",
].filter(Boolean).join("\n");

if (!html.includes("<!-- seo:start")) {
  console.error("index.html has no <!-- seo:start --> marker");
  process.exit(1);
}
html = html.replace(/<!-- seo:start[\s\S]*?<!-- seo:end -->/, block);
writeFileSync(htmlPath, html);

const pages = ["", "privacy", "terms"].filter((p) => !p || existsSync(join(root, `${p}.html`)));
if (url) {
  const today = new Date().toISOString().slice(0, 10);
  writeFileSync(
    join(root, "sitemap.xml"),
    `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n` +
      pages.map((p) => `  <url><loc>${url}/${p}</loc><lastmod>${today}</lastmod><priority>${p ? "0.3" : "1.0"}</priority></url>`).join("\n") +
      `\n</urlset>\n`
  );
}
writeFileSync(join(root, "robots.txt"), `User-agent: *\nAllow: /\n${url ? `\nSitemap: ${url}/sitemap.xml\n` : ""}`);

console.log(`SEO updated${url ? ` for ${url}` : " (no domain yet)"}: ${faqs.length} FAQs, ${services.length} services${url ? ", sitemap.xml written" : ""}.`);
